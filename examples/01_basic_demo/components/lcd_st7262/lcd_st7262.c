/* ==================== 绘图函数 ==================== */
void lcd_draw_string(uint16_t *fb, int x, int y, const char *str,
                     uint16_t fg, uint16_t bg)
{
    int sx = x;
    while (*str) {
        if (*str == '\n') { x = sx; y += 16; str++; continue; }
        char c = *str;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *f = font_8x16_data[c - 32];
        for (int r = 0; r < 16; r++) {
            uint8_t d = f[r];
            for (int cl = 0; cl < 8; cl++) {
                int px = x + cl, py = y + r;
                if (px >= 0 && px < LCD_H_RES && py >= 0 && py < LCD_V_RES)
                    fb[py * LCD_H_RES + px] = (d & (0x80 >> cl)) ? fg : bg;
            }
        }
        x += 8; str++;
    }
}

void lcd_clear(uint16_t *fb, uint16_t color) {
    for (int i = 0; i < LCD_H_RES * LCD_V_RES; i++) fb[i] = color;
}

uint16_t rgb888_to_rgb565(uint8_t r, uint8_t g, uint8_t b) {
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | ((b & 0xF8) >> 3);
}

